const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const modelPath = path.join(__dirname, '../assets/js/async-knowledge-state.js');
assert.ok(fs.existsSync(modelPath), 'Knowledge review state model is missing');
const sandbox = {};
vm.runInNewContext(fs.readFileSync(modelPath, 'utf8'), sandbox);
const model = sandbox.AsyncKnowledgeState;
const now = Date.parse('2026-10-15T04:00:00Z');
const state = model.empty();
model.select(state, 'event');
model.write(state, 'event', 'recall', '通知与独占的区别', now);
assert.equal(state.records.event.level, null, 'Viewing and drafting must not grade');
assert.equal(model.due(state, now).length, 0);
model.attempt(state, 'event', 'wrong', false, now);
assert.equal(state.records.event.level, null, 'An attempt must not assign mastery');
assert.equal(model.due(state, now)[0], 'event');
model.grade(state, 'event', 'explain', now);
assert.equal(state.records.event.dueAt, now + 3 * 86400000);
assert.equal(model.due(state, now).length, 0, 'A deliberate grade resolves the current failed attempt');
assert.equal(model.due(state, now + 3 * 86400000)[0], 'event');
model.write(state, 'event', 'note', 'set 不等于等待者已执行完。', now + 1);
assert.equal(state.records.event.dueAt, now + 3 * 86400000, 'Editing notes does not postpone review');
const backup = model.serialize(state);
const restored = model.parse(backup);
assert.equal(restored.records.event.note, state.records.event.note);
assert.equal(restored.selected, 'event');
const before = model.serialize(state);
for (const bad of ['{', '{}', '{"schema_version":9,"records":{}}', '{"schema_version":1,"records":{"__proto__":{}}}', '{"schema_version":1,"records":{"event":{"level":"mastered"}}}']) {
  assert.throws(() => model.parse(bad));
  assert.equal(model.serialize(state), before, 'Invalid import must not modify existing records');
}
const newer = model.parse(backup);
model.write(newer, 'event', 'note', '更新的记录', now + 100);
model.write(newer, 'lock', 'note', '完整保护读改写', now + 100);
model.merge(newer, restored);
assert.equal(newer.records.event.note, '更新的记录', 'Older import must not overwrite newer notes');
assert.equal(newer.records.lock.note, '完整保护读改写');
const importedTimestamp = newer.records.event.updatedAt;
model.write(newer, 'event', 'note', '导入以后仍可继续修改', now);
assert.ok(newer.records.event.updatedAt > importedTimestamp, 'Edits must advance an imported timestamp even when clocks differ');
assert.equal(newer.records.event.note, '导入以后仍可继续修改');
model.grade(newer, 'lock', 'review', now);
assert.equal(newer.records.lock.dueAt, now + 86400000);
model.grade(newer, 'lock', 'apply', now);
assert.equal(newer.records.lock.dueAt, now + 7 * 86400000);
assert.throws(() => model.write(newer, '__proto__', 'note', 'bad', now));
assert.throws(() => model.grade(newer, 'lock', 'mastered', now));
console.log('Knowledge state: recall, due dates, import validation and merge passed');
